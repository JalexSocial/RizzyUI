# Regenerates src/RizzyUI/Utility/RzDirectiveRules.g.cs (decision D-27): per component, whether its root
# manages its own visibility (x-show/x-transition), which attributes it computes with x-bind, and its
# x-ref names. Run: python eng/generate-directive-rules.py
import os, re
import sys
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'RizzyUI'))
root='Components'
rows=[]
OVERRIDABLE={'role','data-slot','type'}
for dp,_,fs in sorted(os.walk(root)):
    for f in sorted(fs):
        if not f.endswith('.razor'): continue
        s=open(os.path.join(dp,f),encoding='utf-8').read()
        name=f[:-6]
        tags=re.findall(r'<[A-Za-z][^<>]*?(?:/>|>)', s, re.S)
        root_tags=[t for t in tags if '@attributes' in t]
        vis=any(re.search(r'\sx-show[=\s]|\sx-transition',t) for t in root_tags)
        computed=set()
        for t in root_tags:
            for m in re.finditer(r'\s(?:x-bind:|:)([a-zA-Z][\w-]*)=', t):
                if m.group(1) not in OVERRIDABLE: computed.add(m.group(1))
        refs=set(re.findall(r'\sx-ref="([A-Za-z_][\w]*)"', s))
        if vis or computed or refs:
            rows.append((name,vis,sorted(computed),sorted(refs)))
def arr(xs): return '[' + ', '.join('"%s"'%x for x in xs) + ']'
lines=[f'        ["{n}"] = new({str(v).lower()}, {arr(c)}, {arr(r)}),' for n,v,c,r in rows]
src='''// <auto-generated>
// Generated from the components' Razor markup by eng/generate-directive-rules.py; do not edit.
// DirectiveRulesTests fails when it is out of date.
// </auto-generated>
using System.Collections.Frozen;

namespace RizzyUI;

internal static partial class RzDirectiveRules
{
    private static readonly FrozenDictionary<string, Rule> Generated = new Dictionary<string, Rule>(StringComparer.Ordinal)
    {
''' + '\n'.join(lines) + '''
    }.ToFrozenDictionary(StringComparer.Ordinal);
}
'''
open('Utility/RzDirectiveRules.g.cs','w',encoding='utf-8',newline='\r\n').write(src)
print(len(rows))
